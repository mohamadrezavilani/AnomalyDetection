def read_window(source,cursor=None):
    from .product_source import bounded_semantic_select
    cursor=cursor or {}
    with source.snapshot() as q:
        meta=source.metadata(q);target=cursor.get('target_ns')
        floor=meta.get('analysis_floor_ns',0)
        if floor and target is not None and target<floor:
            cursor={'next_ns':floor}
            target=None
        if floor and max(floor,target or floor)+FIVE_NS>meta['next_ns']:
            return {'source':meta,'target_ns':None,'rows':[]}
        if target is None:
            target=max(effective_floor(meta),cursor.get('next_ns',max(FIVE_NS,meta['next_ns']-2*FIVE_NS)))
            found=q('SELECT start_ns,end_ns,generation,last_publish_ns FROM (SELECT start_ns,end_ns,generation,last_publish_ns '
                'FROM public.viewer_live_windows WHERE start_ns>=%s AND end_ns<=%s ORDER BY start_ns LIMIT 1) AS available',
                (target,meta['next_ns']),cap=1)
        else:found=q('SELECT start_ns,end_ns,generation,last_publish_ns FROM public.viewer_live_windows WHERE start_ns=%s',(target,),cap=1)
        if not found:
            if cursor.get('target_ns') is not None and cursor['target_ns']<meta['next_ns']:
                return {'source':meta,'target_ns':cursor['target_ns'],'rows':[],'available':False,'has_more':False}
            return {'source':meta,'target_ns':None,'rows':[]}
        window=found[0];target=window['start_ns']
        if target<meta['retention_cutoff_ns'] or window['end_ns']!=target+FIVE_NS:
            return {'source':meta,'target_ns':target,'available':False,'rows':[],'has_more':False}
        # Global generation also fences catalog/reconciliation changes that do
        # not change the per-window receipt. Never combine two RR snapshots.
        stamp=digest([window,meta['generation'],meta['semantic_generation'],meta['catalog_fingerprint']])
        if cursor.get('stamp') and cursor['stamp']!=stamp:
            return {'source':meta,'target_ns':target,'restart':True,'stamp':stamp,'rows':[]}
        after=cursor.get('after');params=[target,target+FIVE_NS]
        clause=''
        if after:clause='AND (s.anchor_ns,s.request_key)>(%s,%s) ';params.extend(after)
        statement=bounded_semantic_select("WHERE s.state='active' AND s.anchor_ns>=%s AND s.anchor_ns<%s "+clause,
            's.anchor_ns,s.request_key')
        rows=q('SELECT * FROM ('+statement+') AS window_page',(*params,source.page_size+1),cap=source.page_size+1)
        more=len(rows)>source.page_size;rows=rows[:source.page_size]
        return {'source':meta,'target_ns':target,'stamp':stamp,'available':True,'rows':rows,'has_more':more,
            'after':[rows[-1]['anchor_ns'],rows[-1]['request_key']] if more else None}

def apply_window(store,packet,*,cursor_name='fresh_cursor'):
    target=packet['target_ns']
    if target is None or target<store.history_floor_ns:return {'status':'CAUGHT_UP'}
    with store.transaction():
        store.bind(packet['source'])
        previous_proof=store.raw.execute('SELECT stamp,complete FROM anomaly_detection.adp_source_windows WHERE start_ns=%s',(target,)).fetchone()
        def discard():
            store.raw.execute('DELETE FROM anomaly_detection.adp_window_staging WHERE lane=%s AND start_ns=%s',(cursor_name,target))
        if packet.get('available') and not packet.get('restart') and previous_proof and previous_proof['complete'] and previous_proof['stamp']==packet['stamp']:
            discard();store.save_state(cursor_name,{'next_ns':target+FIVE_NS})
            return {'status':'ALREADY_COMPLETE'}
        if packet.get('restart'):
            # A rejected snapshot never clears another lane or the last
            # successfully published population.
            discard();store.save_state(cursor_name,{'target_ns':target})
            return {'status':'RESTART_SNAPSHOT'}
        if not packet.get('available'):
            from .population import enqueue
            enqueue(store,[target])
            discard()
            unavailable=dict(packet['source'],quality_reason='SOURCE_WINDOW_UNAVAILABLE')
            store.raw.execute('UPDATE anomaly_detection.adp_source_windows SET complete=FALSE,source=%s WHERE start_ns=%s',(canonical(unavailable),target))
            from .longitudinal import coverage_changed
            coverage_changed(store,target)
            # A retained, previously qualified reference is learning history,
            # not a claim of current source availability. Known retention must
            # not erase that history or turn it into a zero. Unexpected loss
            # stays ineligible until a complete replacement is observed.
            if target>=packet['source'].get('retention_cutoff_ns',0):
                store.raw.execute('UPDATE anomaly_detection.adp_service_reference_points SET qualified=FALSE WHERE start_ns=%s',(target,))
            impacted=store.raw.execute('SELECT session_key,body FROM anomaly_detection.adp_windows WHERE start_ns=%s',(target,)).fetchall()
            store.invalidate_many([(r['session_key'],target) for r in impacted],create_targets=[])
            from .product_dependencies import context_changed_many
            context_changed_many(store,[(service,target) for r in impacted for service in (json.loads(r['body']).get('counts') or {})])
            store.save_state(cursor_name,{'next_ns':target+FIVE_NS})
            return {'status':'UNAVAILABLE'}
        cursor=store.state(cursor_name)
        if not cursor.get('after'):discard()
        else:require(cursor.get('stamp')==packet['stamp'],'WINDOW_STAGE_STAMP_MISMATCH')
        from .product_store import core
        require(len({r['request_key'] for r in packet['rows']})==len(packet['rows']),'DUPLICATE_WINDOW_MEMBER')
        for row in packet['rows']:
            value=core(row)
            require(target<=value['anchor_ns']<target+FIVE_NS,'WINDOW_MEMBER_OUTSIDE_TARGET')
        values=[{'request_key':r['request_key'],'body':r} for r in packet['rows']]
        if values:
            store.raw.execute('INSERT INTO anomaly_detection.adp_window_staging '
                "SELECT %s,%s,%s,v->>'request_key',(v->'body')::text FROM jsonb_array_elements(%s::jsonb) AS v "
                'ON CONFLICT(lane,start_ns,request_key) DO UPDATE SET stamp=excluded.stamp,body=excluded.body',
                (cursor_name,target,packet['stamp'],canonical(values)))
        if packet['has_more']:
            store.save_state(cursor_name,{'target_ns':target,'after':packet['after'],'stamp':packet['stamp']})
            return {'status':'READING','rows':len(packet['rows'])}
        staged=store.raw.execute('SELECT body,stamp FROM anomaly_detection.adp_window_staging WHERE lane=%s AND start_ns=%s ORDER BY request_key',(cursor_name,target)).fetchall()
        require(all(r['stamp']==packet['stamp'] for r in staged),'WINDOW_STAGE_STAMP_MISMATCH')
        rows=[json.loads(r['body']) for r in staged]
        # Facts, summaries, complete membership, peers, dependencies and cursor
        # now change in one owned transaction. No partial population is visible.
        for begin in range(0,len(rows),4096):store.apply_rows(rows[begin:begin+4096],packet['source'])
        grouped=defaultdict(list)
        for row in rows:
            if row.get('session_key'):grouped[row['session_key']].append(row)
        old={r['session_key']:json.loads(r['body']) for r in store.raw.execute('SELECT session_key,body FROM anomaly_detection.adp_windows WHERE start_ns=%s',(target,)).fetchall()}
        changed=[];contexts=[];summaries=[];versions=[];replacements=[]
        for session in sorted(grouped.keys()|old.keys()):
            members=grouped[session];counts=defaultdict(int);witnesses={};kinds={}
            valid=True;unmapped=0;kind_counts=defaultdict(int)
            for r in members:
                service=api_path(r.get('root_call'))
                if r.get('kind') not in KINDS or r.get('identity_state')!='assigned' or r.get('conflicted') or r.get('request_session_key')!=session:
                    valid=False;continue
                kind_counts[r['kind']]+=1
                if not service:unmapped+=1;continue
                counts[service]+=1;witnesses.setdefault(service,r['request_key']);kinds[service]=r['kind']
            membership=digest([[r.get(k) for k in ('request_key','anchor_key','anchor_ns','revision','kind','root_call','root_code','identity_state','conflicted','request_session_key')] for r in members])
            body={'start_ns':target,'coverage_complete':valid,'population_complete':valid,'counts':dict(counts) if valid else None,
                'witnesses':witnesses,'count_kinds':kinds,'kind_counts':dict(kind_counts),'unmapped_behaviors':unmapped,
                'count_scope':'RESOLVED_SERVICE_PATHS','membership_digest':membership,'first_observed_ns':None,'quality_reason':'COMPLETE_WINDOW_SNAPSHOT',
                'provenance':{'source_generation':packet['source']['generation'],'observed_ns':packet['source']['captured_at_ns'],'stamp':packet['stamp'],'scope_contract':'atomic-lane-window-v3'}}
            from .job_scope import projection
            previous=old.get(session)
            summary={'session_key':session,'start_ns':target,'body':body,
                     'observed_count':sum(counts.values()) if valid else 0}
            if projection(previous)!=projection(body):
                changed.append((session,target))
                contexts.extend((service,target) for service in set((previous or {}).get('counts') or {})|set(counts))
                if previous:versions.append({'session_key':session,'start_ns':target,'body':previous})
                replacements.append(dict(summary,content_digest=digest(body)))
            if members:
                summaries.append(summary)
        if versions:
            store.raw.execute("INSERT INTO anomaly_detection.adp_window_versions(session_key,start_ns,body,reason,observed_ns) SELECT v->>'session_key',(v->>'start_ns')::bigint,(v->'body')::text,'replaced_complete_snapshot',%s FROM jsonb_array_elements(%s::jsonb) AS v",
                (packet['source']['captured_at_ns'],canonical(versions)))
        # The shared receipt below records the latest publication. Keep the
        # first provenance of an unchanged session projection. This avoids
        # rewriting thousands of empty/context-only rows on overlap replays.
        for offset in range(0,len(replacements),256):
            store.raw.execute("INSERT INTO anomaly_detection.adp_windows SELECT v->>'session_key',(v->>'start_ns')::bigint,(v->'body')::text,v->>'content_digest' FROM jsonb_array_elements(%s::jsonb) AS v "
                'ON CONFLICT(session_key,start_ns) DO UPDATE SET body=excluded.body,content_digest=excluded.content_digest',
                (canonical(replacements[offset:offset+256]),))
        store.raw.execute('DELETE FROM anomaly_detection.adp_window_members WHERE start_ns=%s',(target,))
        store.raw.execute('INSERT INTO anomaly_detection.adp_window_members SELECT start_ns,request_key,body FROM anomaly_detection.adp_window_staging WHERE lane=%s AND start_ns=%s',(cursor_name,target))
        store.invalidate_many(changed,create_targets=[(s,target) for s in grouped if grouped[s]])
        counts=[{'session_key':row['session_key'],'n':row['observed_count']} for row in summaries]
        counts.extend({'session_key':row['session_key'],'n':0} for row in replacements if not grouped[row['session_key']])
        for offset in range(0,len(counts),256):
            store.raw.execute("UPDATE anomaly_detection.adp_jobs j SET observed_count=x.n "
                "FROM jsonb_to_recordset(%s::jsonb) AS x(session_key TEXT,n BIGINT) "
                "WHERE j.session_key=x.session_key AND j.target_ns=%s AND j.observed_count IS DISTINCT FROM x.n",
                (canonical(counts[offset:offset+256]),target))
        from .product_dependencies import context_changed_many
        context_changed_many(store,contexts)
        source_proof=dict(packet['source'],scope_contract='atomic-lane-window-v3',peer_population_valid=all(r.get('identity_state')=='assigned' and not r.get('conflicted') and r.get('request_session_key')==r.get('session_key') for r in rows if r.get('session_key')))
        store.raw.execute('INSERT INTO anomaly_detection.adp_source_windows VALUES(%s,%s,%s,TRUE) ON CONFLICT(start_ns) '
            'DO UPDATE SET stamp=excluded.stamp,source=excluded.source,complete=TRUE',(target,packet['stamp'],canonical(source_proof)))
        from .longitudinal import coverage_changed,publish as publish_longitudinal
        coverage_changed(store,target)
        publish_longitudinal(store,target,summaries)
        from .population import enqueue
        enqueue(store,[target])
        refresh_cohort(store,target);discard();store.save_state(cursor_name,{'next_ns':target+FIVE_NS})
        return {'status':'COMPLETE','behaviors':len(rows),'sessions':len(grouped)}

def read_window_burst(source,store,*,clock,cursor_name='fresh_cursor',initial_cursor=None,max_pages=4,max_seconds=1.5,progress=None):
    """Finish bounded adjacent pages promptly; every read keeps the full fence.

    There is no transaction spanning pages. Partial rows stay in lane staging,
    and a generation change still restarts the entire unpublished population.
    """
    deadline=clock.monotonic()+max_seconds
    results=[]
    for index in range(max_pages):
        cursor=initial_cursor if index==0 and initial_cursor is not None else store.state(cursor_name)
        if progress:progress('read')
        packet=read_window(source,cursor)
        if progress:progress('apply')
        result=apply_window(store,packet,cursor_name=cursor_name)
        results.append(result)
        if result['status'] not in ('READING','RESTART_SNAPSHOT') or clock.monotonic()>=deadline:
            break
    return results


def read_fresh_burst(source,store,*,clock,max_pages=4,max_seconds=1.5):
    return read_window_burst(source,store,clock=clock,max_pages=max_pages,max_seconds=max_seconds)

def refresh_cohort(store,target):
    proof=store.raw.execute('SELECT source,complete FROM anomaly_detection.adp_source_windows WHERE start_ns=%s',(target,)).fetchone()
    if not proof or not proof['complete']:return
    source=json.loads(proof['source']);values=defaultdict(list)
    rows=store.raw.execute('SELECT w.session_key,w.body FROM anomaly_detection.adp_windows w WHERE w.start_ns=%s AND NOT EXISTS('
        'SELECT 1 FROM anomaly_detection.adp_incidents i JOIN anomaly_detection.adp_feedback f ON f.incident_key=i.incident_key '
        "WHERE i.session_key=w.session_key AND i.target_ns=w.start_ns AND f.label='confirmed_suspicious' "
        'AND f.id=(SELECT MAX(v.id) FROM anomaly_detection.adp_feedback v WHERE v.incident_key=i.incident_key))',(target,)).fetchall()
    from .service_reference import refresh_points
    refresh_points(store,target,source,rows)
    for row in rows:
        body=json.loads(row['body'])
        if not body.get('population_complete') or not body.get('coverage_complete'):continue
        for service,n in (body.get('counts') or {}).items():
            if n>0:values[service].append(n)
    import math
    cohort=[{'service_path':service,'value':sorted(ns)[max(0,math.ceil(.95*len(ns))-1)],'sessions':len(ns),
        'population_valid':int(source.get('peer_population_valid',False))} for service,ns in sorted(values.items())]
    store.apply_cohort({'source':source,'target_ns':target,'rows':cohort,'available':True,'owned_snapshot':True},advance=False)

def owned_context(store,job):
    """Qualified sparse summaries + shared complete-window coverage, no source scan."""
    target=job['target_ns'];begin=max(FIVE_NS,store.history_floor_ns,target-56*288*FIVE_NS);session=job['session_key']
    proof=store.raw.execute('SELECT source,complete FROM anomaly_detection.adp_source_windows WHERE start_ns=%s',(target,)).fetchone()
    if not proof or not proof['complete']:return None
    source=json.loads(proof['source'])
    windows={r['start_ns']:json.loads(r['body']) for r in store.raw.execute('SELECT start_ns,body FROM anomaly_detection.adp_windows WHERE session_key=%s AND start_ns>=%s AND start_ns<=%s',(session,begin,target)).fetchall()}
    first=store.raw.execute('SELECT MIN(at_ns) AS first_ns FROM anomaly_detection.adp_facts WHERE session_key=%s',(session,)).fetchone()['first_ns']
    for r in store.raw.execute('SELECT start_ns FROM anomaly_detection.adp_source_windows WHERE complete=TRUE AND start_ns>=%s AND start_ns<=%s',(max(begin,source.get('retention_cutoff_ns',0)),target)).fetchall():
        at=r['start_ns']
        if first is not None and at>=first//FIVE_NS*FIVE_NS:
            windows.setdefault(at,{'start_ns':at,'coverage_complete':True,'population_complete':True,'counts':{},'witnesses':{},'first_observed_ns':first})
    current=windows.get(target)
    if not current:return None
    facts=store.raw.execute('SELECT body FROM anomaly_detection.adp_facts WHERE session_key=%s AND at_ns>=%s AND at_ns<%s '
        "AND state='active' AND eligible=TRUE AND source_present=TRUE "
        'AND (NOT EXISTS(SELECT 1 FROM anomaly_detection.adp_source_windows w WHERE w.start_ns=(adp_facts.at_ns/%s)*%s) '
        'OR EXISTS(SELECT 1 FROM anomaly_detection.adp_window_members m WHERE m.start_ns=(adp_facts.at_ns/%s)*%s AND m.request_key=adp_facts.request_key)) '
        'ORDER BY at_ns DESC,request_key DESC LIMIT 2049',(session,begin,target+FIVE_NS,FIVE_NS,FIVE_NS,FIVE_NS,FIVE_NS)).fetchall()
    events=sorted([json.loads(r['body']) for r in facts[:2048]],key=lambda r:(r['anchor_ns'],r['request_key']))
    return {'source':source,'session_key':session,'target_ns':target,'windows':sorted(windows.values(),key=lambda r:r['start_ns']),
        'events':events,'target_complete':current['coverage_complete'],'target_events_complete':len(facts)<=2048 or bool(events and events[0]['anchor_ns']<target),
        'history_truncated':False,'event_history_truncated':len(facts)>2048,'history_scope':'OWNED_QUALIFIED_WINDOW_SUMMARIES',
        'evidence_verified':False,'coverage_is_source_finality':False,'owned_snapshot':True}
