def next_profile(store,now,*,independent=False,historical=False):
    record_queue_write(store,'profile_ready_promotion',promote(store,'adp_profile_tasks',now))
    if historical:
        # An ordered pass advances even as new live scopes arrive. Tasks not
        # due yet remain available on the next pass after their own backoff.
        state=store.state('profile_history_pass_v1')
        query='SELECT request_key FROM anomaly_detection.adp_profile_tasks WHERE due_ns=0 '
        row=store.raw.execute(query+'AND request_key>%s ORDER BY request_key LIMIT 1',(state.get('after',''),)).fetchone()
        if not row and state.get('after'):
            row=store.raw.execute(query+'ORDER BY request_key LIMIT 1').fetchone()
        if row:
            store.save_state('profile_history_pass_v1',{'after':row['request_key']})
            return row['request_key']
    if independent:
        row=store.raw.execute(PROFILE_INDEPENDENT).fetchone()
        if row:return row['request_key']
    state=store.state('profile_active_scope_v1') if not independent else {}
    if state.get('keys'):
        row=store.raw.execute('SELECT request_key FROM anomaly_detection.adp_profile_tasks WHERE request_key=ANY(%s) AND due_ns=0 ORDER BY request_key LIMIT 1',(state['keys'],)).fetchone()
        if row:return row['request_key']
    scope=store.raw.execute(profile_scope_query(independent)).fetchone()
    if scope:
        keys=json.loads(scope['request_keys'])
        if not independent:store.save_state('profile_active_scope_v1',{'keys':keys})
        row=store.raw.execute('SELECT request_key FROM anomaly_detection.adp_profile_tasks WHERE request_key=ANY(%s) AND due_ns=0 ORDER BY request_key LIMIT 1',(keys,)).fetchone()
        if row:return row['request_key']
    row=store.raw.execute('SELECT request_key FROM anomaly_detection.adp_profile_tasks WHERE due_ns=0 ORDER BY priority DESC,request_key LIMIT 1').fetchone()
    return row['request_key'] if row else None


def profile_current(profile,row):
    """Schema, canonical revision and pending refresh are separate guards.

    Independent technical samples may legitimately have no canonical AD Fact.
    A profile claiming a semantic anchor requires that exact active Fact.
    """
    if profile.get('version')!=PROFILE_VERSION or row.get('refresh_pending'):return False
    if profile.get('semantic_active') or row.get('state')=='active':
        return bool(row.get('revision') is not None and row.get('state')=='active' and row.get('source_present')
            and row['revision']==profile.get('semantic_revision') and row.get('anchor_key')==profile.get('anchor_key'))
    return True


def scope_profiles(store,session,service,target,cache=None):
    row=cache[0].get((session,service,target)) if cache else store.raw.execute('SELECT * FROM anomaly_detection.adp_profile_scopes WHERE session_key=%s AND service_path=%s AND start_ns=%s',(session,service,target)).fetchone()
    if not row:return [],False,False
    keys=json.loads(row['request_keys']);records=[cache[1][k] for k in keys if k in cache[1]] if cache else store.raw.execute('SELECT p.request_key,p.body,f.revision,f.anchor_key,f.source_present,f.state,EXISTS(SELECT 1 FROM anomaly_detection.adp_profile_tasks t WHERE t.request_key=p.request_key) AS refresh_pending FROM anomaly_detection.adp_profiles p LEFT JOIN anomaly_detection.adp_facts f USING(request_key) WHERE p.request_key=ANY(%s)',(keys,)).fetchall()
    data=[]
    for r in records:
        p=json.loads(r['body'])
        if not profile_current(p,r):p['qualified']=False
        p['_training_quarantined']=r.get('training_quarantined',False)
        if p['session_key']!=session or not p.get('actor_qualified',True) or service!='*' and p['service_path']!=service:p['qualified']=False
        data.append(p)
    complete=bool(row['available'] and keys and len(data)==len(keys) and all(p.get('qualified') and target<=p['at_ns']<target+FIVE_NS for p in data))
    return data,complete,row['independent']


def volume_history(store,service,target,*,canonical_scope):
    """Eligible, unreviewed volume findings do not silently become normal.

    A benign review grants the reviewed case revision only. Current job-token
    rewrites alone must not revoke that review; changed evidence/case content
    does. Technical and meaningful-execution count scopes remain separate.
    """
    from .cases import identity
    table='adp_population' if canonical_scope else 'adp_traffic_counts'
    scope='canonical_meaningful_executions' if canonical_scope else 'complete_root_client_request_census'
    key=identity('service',service,'service_volume',service)
    rows=store.raw.execute("WITH blocked AS (SELECT s.target_ns FROM anomaly_detection.adp_case_signals s JOIN anomaly_detection.adp_cases c USING(case_key) WHERE s.case_key=%s AND s.family='service_volume' AND s.state='ACTIVE' AND s.qualified=TRUE AND s.review_eligible=TRUE AND s.body::jsonb->>'count_scope'=%s AND COALESCE((SELECT b.label FROM anomaly_detection.adp_case_feedback b WHERE b.case_key=s.case_key AND b.case_revision=c.revision AND b.reviewed_end_ns>=s.end_ns ORDER BY b.id DESC LIMIT 1),'unreviewed')<>'reviewed_benign') SELECT p.body FROM anomaly_detection."+table+" p WHERE p.service_path=%s AND p.start_ns<%s AND p.start_ns>=%s AND NOT EXISTS(SELECT 1 FROM blocked b WHERE b.target_ns=p.start_ns) ORDER BY p.start_ns LIMIT 16128",(key,scope,service,target,target-HORIZON)).fetchall()
    return [json.loads(r['body']) for r in rows]


