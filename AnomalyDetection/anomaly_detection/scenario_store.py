def queue_keys(store,keys,priority=0,*,force=False):
    keys=sorted(set(keys))
    if not keys:return
    if not force:
        present={r['request_key'] for r in store.raw.execute("SELECT request_key FROM anomaly_detection.adp_profiles WHERE request_key=ANY(%s) AND body::jsonb->>'version'=%s",(keys,PROFILE_VERSION)).fetchall()}
        keys=[k for k in keys if k not in present]
    if keys:
        update='priority=GREATEST(adp_profile_tasks.priority,excluded.priority)'+(',due_ns=0' if force else '')
        needed='adp_profile_tasks.priority<excluded.priority'+(' OR adp_profile_tasks.due_ns<>0' if force else '')
        cursor=store.raw.execute('INSERT INTO anomaly_detection.adp_profile_tasks(request_key,priority) SELECT x,%s FROM unnest(%s::text[]) x ON CONFLICT(request_key) DO UPDATE SET '+update+' WHERE '+needed,(priority,keys))
        record_queue_write(store,'profile_task_enqueue',cursor)


def publish_scope(store,session,service,target,keys,*,independent=False,available=True,authority='canonical'):
    keys=sorted(set(keys));value=canonical(keys)
    old=store.raw.execute('SELECT * FROM anomaly_detection.adp_profile_scopes WHERE session_key=%s AND service_path=%s AND start_ns=%s',(session,service,target)).fetchone()
    if old and old['authority']=='root_census' and old['available'] and authority=='canonical':return
    if old and old['request_keys']==value and old['available']==available and old['authority']==authority and (old['independent'] or not independent):return
    store.raw.execute('INSERT INTO anomaly_detection.adp_profile_scopes VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(session_key,service_path,start_ns) DO UPDATE SET request_keys=excluded.request_keys,independent=adp_profile_scopes.independent OR excluded.independent,available=excluded.available,authority=excluded.authority',(session,service,target,value,independent,available,authority))
    store.raw.execute('DELETE FROM anomaly_detection.adp_profile_scope_members WHERE session_key=%s AND service_path=%s AND start_ns=%s',(session,service,target))
    if keys:store.raw.execute('INSERT INTO anomaly_detection.adp_profile_scope_members SELECT %s,%s,%s,k FROM unnest(%s::text[]) k',(session,service,target,keys))
    queue_keys(store,keys,priority=2 if len(keys)>=8 else 0)
    enqueue(store,'actor',session,service,target)
    if independent and service!='*':enqueue(store,'response',service,service,target)


def save_profile(store,packet,now):
    key=packet['request_key'];profile=packet.get('profile')
    with store.transaction():
        store.bind(packet['source'])
        old=store.raw.execute('SELECT p.*,EXISTS(SELECT 1 FROM anomaly_detection.adp_profile_tasks t WHERE t.request_key=p.request_key) AS refresh_pending FROM anomaly_detection.adp_profiles p WHERE p.request_key=%s',(key,)).fetchone()
        if profile is None:
            if not old:
                store.raw.execute('UPDATE anomaly_detection.adp_profile_tasks SET due_ns=%s,attempts=attempts+1 WHERE request_key=%s',(now+60_000_000_000,key));return
            profile=json.loads(old['body'])|{'qualified':False,'issues':['SOURCE_REQUEST_UNAVAILABLE']}
        if not profile.get('service_path') or not profile.get('at_ns'):
            store.raw.execute('UPDATE anomaly_detection.adp_profile_tasks SET due_ns=%s,attempts=attempts+1 WHERE request_key=%s',(now+60_000_000_000,key));return
        if profile['at_ns']<store.history_floor_ns:
            store.raw.execute('DELETE FROM anomaly_detection.adp_profile_tasks WHERE request_key=%s',(key,))
            if old:
                store.raw.execute('DELETE FROM anomaly_detection.adp_profiles WHERE request_key=%s',(key,))
                changed(store,[old['service_path']],old['at_ns'],profile_only=True)
            return
        signature=digest(profile)
        content_changed=old is None or old['content_digest']!=signature
        if content_changed:
            store.raw.execute('INSERT INTO anomaly_detection.adp_profiles VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(request_key) DO UPDATE SET session_key=excluded.session_key,service_path=excluded.service_path,at_ns=excluded.at_ns,body=excluded.body,content_digest=excluded.content_digest,observed_ns=excluded.observed_ns',(key,profile['session_key'],profile['service_path'],profile['at_ns'],canonical(profile),signature,now))
            store.raw.execute('INSERT INTO anomaly_detection.adp_profile_versions(request_key,body,content_digest,observed_ns) VALUES(%s,%s,%s,%s)',(key,canonical(profile),signature,now))
            services=[profile['service_path']]
            if old:
                services.append(old['service_path'])
            changed(store,services,min(profile['at_ns'],old['at_ns'] if old else profile['at_ns']),profile_only=True)
        if profile.get('qualified'):
            store.raw.execute('DELETE FROM anomaly_detection.adp_profile_tasks WHERE request_key=%s',(key,))
            # A completed refresh is an input transition even when its feature
            # body is unchanged. Previously deferred consumers must run again.
            if old and old.get('refresh_pending') and not content_changed:
                changed(store,[profile['service_path']],profile['at_ns'],profile_only=True)
        else:store.raw.execute('UPDATE anomaly_detection.adp_profile_tasks SET due_ns=%s,attempts=attempts+1 WHERE request_key=%s',(now+60_000_000_000,key))


