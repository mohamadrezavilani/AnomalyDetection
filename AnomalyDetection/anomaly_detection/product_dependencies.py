def peer_model(store,service,target):
    from .temporal import fit,Point
    with store.transaction():
        store.raw.execute('INSERT INTO anomaly_detection.adp_peer_epochs VALUES(%s,0) ON CONFLICT DO NOTHING',(service,))
        epoch=store.raw.execute('SELECT version FROM anomaly_detection.adp_peer_epochs WHERE service_path=%s FOR SHARE',(service,)).fetchone()['version']
        cache_key=(service,target,epoch)
        if cache_key not in store.model_cache:
            rows=store.peer(service,target)
            model=fit([Point(r['start_ns'],r['value'],r['eligible'],r['eligible']) for r in rows],before_ns=target)
            model=dict(model,population_windows=len(rows),qualified_population_windows=sum(bool(r['eligible']) for r in rows))
            if len(store.model_cache)>=256:store.model_cache.clear()
            store.model_cache[cache_key]=model
        return store.model_cache[cache_key],epoch

def commit_dependencies(store,job,inputs):
    # Epoch locks last through the result transaction. A competing peer change
    # cannot slip between the input check and commit.
    for service,epoch in sorted(inputs.items()):
        current=store.raw.execute('SELECT version FROM anomaly_detection.adp_peer_epochs WHERE service_path=%s FOR SHARE',(service,)).fetchone()
        if current is None or current['version']!=epoch:return False
    store.raw.execute('DELETE FROM anomaly_detection.adp_peer_dependencies WHERE session_key=%s AND target_ns=%s',
        (job['session_key'],job['target_ns']))
    for service,epoch in sorted(inputs.items()):
        store.raw.execute('INSERT INTO anomaly_detection.adp_peer_dependencies VALUES(%s,%s,%s,%s,%s)',
            (job['session_key'],job['target_ns'],service,max(FIVE_NS,job['target_ns']-HISTORY_NS),epoch))
    return True

def context_changed_many(store,items):
    scopes={}
    for service,at in items:
        if not service:continue
        low,high=scopes.get(service,(at,at));scopes[service]=(min(low,at),max(high,at))
    _context_scopes_changed(store,scopes)

def context_changed(store,service,at,*,at_high=None):
    if not service:return
    _context_scopes_changed(store,{service:(at,at if at_high is None else at_high)})


def _context_scopes_changed(store,scopes):
    """One bounded page invalidates distinct consumers once, across services.

    Read dependent keys first through the service/time index, then update jobs
    by their composite primary key. No per-service scan of the whole job queue.
    Epochs retain their per-service meaning and CAS still checks every input.
    """
    if not scopes:return
    values=canonical([{'name':'context:'+s,'low_ns':low,'high_ns':high} for s,(low,high) in sorted(scopes.items())])
    source='SELECT * FROM jsonb_to_recordset(%s::jsonb) AS s(name TEXT,low_ns BIGINT,high_ns BIGINT)'
    store.raw.execute('INSERT INTO anomaly_detection.adp_peer_epochs '
        'SELECT name,1 FROM ('+source+') s ORDER BY name '
        'ON CONFLICT(service_path) DO UPDATE SET version=adp_peer_epochs.version+1',(values,))
    store.raw.execute('WITH scopes AS ('+source+'), consumers AS ('
        'SELECT DISTINCT d.session_key,d.target_ns FROM scopes s JOIN anomaly_detection.adp_peer_dependencies d '
        'ON d.service_path=s.name AND d.begin_ns<=s.high_ns AND d.target_ns>s.low_ns), '
        'affected AS (UPDATE anomaly_detection.adp_jobs j SET dirty=TRUE,version=version+1,due_ns=0 '
        'FROM consumers c WHERE j.session_key=c.session_key AND j.target_ns=c.target_ns '
        'RETURNING j.session_key,j.target_ns) '
        "UPDATE anomaly_detection.adp_incidents i SET state='RECHECK_REQUIRED' FROM affected a "
        'WHERE i.session_key=a.session_key AND i.target_ns=a.target_ns',(values,))

def service_details(store,job,services):
    output={};inputs={}
    for service in sorted(set(services)):
        name='context:'+service
        with store.transaction():
            store.raw.execute('INSERT INTO anomaly_detection.adp_peer_epochs VALUES(%s,0) ON CONFLICT DO NOTHING',(name,))
            epoch=store.raw.execute('SELECT version FROM anomaly_detection.adp_peer_epochs WHERE service_path=%s FOR SHARE',(name,)).fetchone()['version']
            inputs[name]=epoch;key=('details',service,job['target_ns'],epoch)
            if key not in store.model_cache:
                rows=store.raw.execute('SELECT f.request_key,f.at_ns,f.service_path,f.details,f.revision,f.anchor_key,j.body AS journey,j.semantic_revision '
                    'FROM anomaly_detection.adp_facts f LEFT JOIN anomaly_detection.adp_journeys j ON j.request_key=f.request_key '
                    'WHERE f.service_path=%s AND f.at_ns>=%s AND f.at_ns<%s AND f.eligible=TRUE AND f.source_present=TRUE AND f.details IS NOT NULL '
                    'AND (NOT EXISTS(SELECT 1 FROM anomaly_detection.adp_source_windows sw WHERE sw.start_ns=(f.at_ns/%s)*%s) '
                    'OR EXISTS(SELECT 1 FROM anomaly_detection.adp_source_windows sw JOIN anomaly_detection.adp_window_members wm ON wm.start_ns=sw.start_ns '
                    'WHERE sw.start_ns=(f.at_ns/%s)*%s AND sw.complete=TRUE AND wm.request_key=f.request_key)) '
                    'AND NOT EXISTS(SELECT 1 FROM anomaly_detection.adp_incidents i JOIN anomaly_detection.adp_feedback b ON b.incident_key=i.incident_key '
                    "WHERE i.session_key=f.session_key AND i.target_ns=(f.at_ns/%s)*%s AND b.label='confirmed_suspicious' "
                    'AND b.id=(SELECT MAX(v.id) FROM anomaly_detection.adp_feedback v WHERE v.incident_key=i.incident_key)) '
                    'ORDER BY f.at_ns DESC,f.request_key DESC LIMIT 2048',
                    (service,job['target_ns']-HISTORY_NS,job['target_ns'],FIVE_NS,FIVE_NS,FIVE_NS,FIVE_NS,FIVE_NS,FIVE_NS)).fetchall()
                values=[]
                for row in rows:
                    fact=json.loads(row['details'])
                    if fact.get('semantic',{}).get('revision')!=row['revision'] or fact.get('semantic',{}).get('anchor_key')!=row['anchor_key']:continue
                    if row['journey'] and row['semantic_revision']==fact.get('semantic',{}).get('revision'):fact['viewer_journey']=json.loads(row['journey'])
                    values.append({'request_key':row['request_key'],'at_ns':row['at_ns'],'service_path':row['service_path'],'details':fact})
                if len(store.model_cache)>=256:store.model_cache.clear()
                store.model_cache[key]=values
            for row in store.model_cache[key]:output[row['request_key']]=row
    return list(output.values()),inputs

def apply_cohort(store,packet,*,advance=True):
    target=packet['target_ns']
    if target is None:return
    with store.transaction():
        if not packet.get('owned_snapshot'):store.bind(packet['source'])
        before={r['service_path']:dict(r) for r in store.raw.execute('SELECT * FROM anomaly_detection.adp_peers WHERE start_ns=%s',(target,)).fetchall()}
        incoming={r['service_path']:r for r in packet['rows']} if packet.get('available',True) else {}
        changed=[]
        for service in sorted(before.keys()|incoming.keys()):
            row=incoming.get(service)
            reason='OBSERVED' if row else 'ABSENT_IN_COMPLETE_REPLACEMENT' if packet.get('available',True) else 'SOURCE_UNAVAILABLE'
            value=row['value'] if row else None
            eligible=bool(row and row['sessions']>=20 and row.get('population_valid',1)==1)
            signature=digest([target,row,reason]);old=before.get(service)
            if old and old['input_digest']==signature:continue
            store.raw.execute('INSERT INTO anomaly_detection.adp_peers VALUES(%s,%s,%s,%s,%s) '
                'ON CONFLICT(service_path,start_ns) DO UPDATE SET value=excluded.value,eligible=excluded.eligible,input_digest=excluded.input_digest',
                (service,target,value,eligible,signature))
            store.raw.execute('INSERT INTO anomaly_detection.adp_peer_versions(service_path,start_ns,body,observed_ns) VALUES(%s,%s,%s,%s)',
                (service,target,canonical({'previous':old,'current':row,'reason':reason}),packet['source']['captured_at_ns']))
            store.raw.execute('INSERT INTO anomaly_detection.adp_peer_epochs VALUES(%s,1) ON CONFLICT(service_path) DO UPDATE SET version=adp_peer_epochs.version+1',(service,))
            changed.append(service)
        if changed:
            # Includes jobs already dirty: their saved context/version is stale too.
            store.raw.execute('WITH affected AS (UPDATE anomaly_detection.adp_jobs j SET dirty=TRUE,version=version+1,due_ns=0 '
                'WHERE EXISTS(SELECT 1 FROM anomaly_detection.adp_peer_dependencies d WHERE d.session_key=j.session_key AND d.target_ns=j.target_ns '
                'AND d.service_path=ANY(%s) AND d.begin_ns<=%s AND d.target_ns>%s) RETURNING j.session_key,j.target_ns) '
                "UPDATE anomaly_detection.adp_incidents i SET state='RECHECK_REQUIRED' FROM affected a "
                'WHERE i.session_key=a.session_key AND i.target_ns=a.target_ns',
                (changed,target,target))
        if advance:store.save_state('cohort_cursor',{'next_ns':target+FIVE_NS})
    return {'changed_services':len(changed)}
